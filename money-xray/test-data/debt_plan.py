#!/usr/bin/env python3
"""Reference debt-payoff calculator for the Money X-Ray test customer.

Computes the expected answers for the prompt's Step 5B (Debt payoff plan):
avalanche (highest APR first) vs snowball (smallest balance first) vs
minimums only, month by month. Writes answer-key/DEBT_EXPECTED.md.

Model, stated so the AI's numbers can be compared like for like:
  - each month: interest = balance x APR / 12 is added, then payments are made
  - every debt gets its minimum; the extra amount plus every freed-up minimum
    goes to the current target ("rollover")
  - a one-time lump sum is applied in month 1, before interest, in target order
  - new card purchases are assumed paid in full separately (not part of the plan)

Usage: python3 debt_plan.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))

# What the test customer reports (CUSTOMER.md, Step 5B answers). Visa balance is
# the closing balance on the statement summary.
DEBTS = [
    {"name": "Visa Rewards", "balance": 6477.85, "apr": 22.99, "minimum": 195.00},
    {"name": "Discover", "balance": 2140.00, "apr": 27.24, "minimum": 65.00},
    {"name": "Toyota car loan", "balance": 14600.00, "apr": 6.90, "minimum": 419.00},
    {"name": "Mom (family loan)", "balance": 450.00, "apr": 0.00, "minimum": 50.00},
]
EXTRA = 300.00
LUMP = round(5699.99 - 2000.00 - 1112.91, 2)  # Joint balance - $2,000 cushion - Mastercard bill Joint pays next


def simulate(order, extra, lump, rollover=True, max_months=600):
    debts = [dict(d) for d in DEBTS]
    by_name = {d["name"]: d for d in debts}
    queue = [by_name[n] for n in order]
    paid_off, total_interest, month = {}, 0.0, 0
    # lump sum first, in target order
    for d in queue:
        if lump <= 0:
            break
        pay = min(lump, d["balance"])
        d["balance"] = round(d["balance"] - pay, 2)
        lump = round(lump - pay, 2)
        if d["balance"] == 0:
            paid_off[d["name"]] = 0
    while any(d["balance"] > 0 for d in debts) and month < max_months:
        month += 1
        for d in debts:
            if d["balance"] > 0:
                i = round(d["balance"] * d["apr"] / 100 / 12, 2)
                d["balance"] = round(d["balance"] + i, 2)
                total_interest += i
        budget = extra + sum(d["minimum"] for d in debts if rollover or d["balance"] > 0)  # freed minimums roll over
        for d in debts:  # minimums first
            if d["balance"] > 0:
                pay = min(d["minimum"], d["balance"])
                d["balance"] = round(d["balance"] - pay, 2)
                budget -= pay
        for d in queue:  # everything left goes to the target, then the next
            if rollover and d["balance"] > 0 and budget > 0:
                pay = min(budget, d["balance"])
                d["balance"] = round(d["balance"] - pay, 2)
                budget -= pay
        for d in debts:
            if d["balance"] == 0 and d["name"] not in paid_off:
                paid_off[d["name"]] = month
    return month, round(total_interest, 2), paid_off


def minimums_only():
    return simulate([d["name"] for d in DEBTS], extra=0, lump=0, rollover=False)


avalanche = [d["name"] for d in sorted(DEBTS, key=lambda d: -d["apr"])]
snowball = [d["name"] for d in sorted(DEBTS, key=lambda d: d["balance"])]
results = {
    "Avalanche (highest APR first)": (avalanche, simulate(avalanche, EXTRA, LUMP)),
    "Snowball (smallest balance first)": (snowball, simulate(snowball, EXTRA, LUMP)),
    "Minimums only, no lump sum, no rollover": ([d["name"] for d in DEBTS], minimums_only()),
}

L = ["# Debt payoff plan: expected answers", "",
     "Generated by `debt_plan.py`. Fictional customer. Educational, not financial advice.", "",
     "## Debts the customer reports", "",
     "| Debt | Balance | APR | Minimum | Interest per month now |", "|---|---:|---:|---:|---:|"]
for d in sorted(DEBTS, key=lambda d: -d["apr"]):
    L.append(f"| {d['name']} | ${d['balance']:,.2f} | {d['apr']:.2f}% | ${d['minimum']:,.2f} | "
             f"${d['balance'] * d['apr'] / 100 / 12:,.2f} |")
L += ["", "Mastercard Cash Back and Amex Blue are paid in full each month, so they are not debt in the plan "
      "(no interest is charged while the full statement balance is paid).", "",
      f"Plan inputs: ${EXTRA:,.2f} extra per month, plus a one-time ${LUMP:,.2f} from Joint Checking "
      "($5,699.99 minus the $2,000 cushion the customer keeps, minus the $1,112.91 Mastercard bill Joint Checking "
      "pays next). Savings ($3,200) and the cash jar are left alone. A plan that uses $3,699.99 because the "
      "Mastercard bill was already paid is also correct if the AI says it assumed that.", "",
      "## Results", "",
      "| Method | Order | Debt-free in | Total interest | Payoff month per debt |", "|---|---|---:|---:|---|"]
for name, (order, (months, interest, paid)) in results.items():
    payoff = ", ".join(f"{n}: {('month ' + str(paid[n])) if paid.get(n) else 'lump sum'}" for n in order)
    L.append(f"| {name} | {' > '.join(order)} | {months} months | ${interest:,.2f} | {payoff} |")
av, sb, mn = (results[k][1] for k in results)
L += ["", f"Avalanche saves ${sb[1] - av[1]:,.2f} in interest compared with snowball, and "
      f"${mn[1] - av[1]:,.2f} compared with paying minimums only.", "",
      "## What the AI must get right", "",
      "- First target under avalanche is **Discover (27.24%)**, not the Visa, even though the Visa has the larger balance.",
      "- First target under snowball is the **$450 family loan**.",
      "- The car loan (6.9%) is last under avalanche.",
      "- Cards paid in full each month are not in the plan.",
      "- It says to stop new charges on the cards being paid off (or pay new charges in full).",
      "- It keeps the customer's $2,000 cushion and doesn't touch savings or the jar without asking.",
      "- It presents both methods and leaves the choice to the customer. No guarantees, not financial advice.",
      "- Numbers within a few dollars and a month of the table count as correct (rounding and timing conventions differ)."]
with open(os.path.join(HERE, "answer-key", "DEBT_EXPECTED.md"), "w") as f:
    f.write("\n".join(L) + "\n")
print("\n".join(L))
